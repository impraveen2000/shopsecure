package com.shopsecure.auth.web;

import com.nimbusds.jose.jwk.JWKSet;
import com.nimbusds.jose.jwk.RSAKey;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

import java.util.Map;

/**
 * JSON Web Key Set endpoint. Resource servers (gateway, product, order, notification) fetch the
 * PUBLIC key from here to verify JWT signatures. toPublicJWK() guarantees the private part is never exposed.
 * Open http://localhost:18081/.well-known/jwks.json to see it.
 */
@RestController
public class JwksController {

    private final RSAKey rsaKey;

    public JwksController(RSAKey rsaKey) {
        this.rsaKey = rsaKey;
    }

    @GetMapping("/.well-known/jwks.json")
    public Map<String, Object> keys() {
        return new JWKSet(rsaKey.toPublicJWK()).toJSONObject();
    }
}
